import JSZip from 'jszip';
import { fetchMeta } from './cinemeta.js';
import { fetchStreams } from './torrentio.js';

export async function createSeasonBatchZip(id, season = 1) {
  const sNum = parseInt(season, 10) || 1;

  // 1. Fetch metadata & episode list
  const meta = await fetchMeta('series', id);
  const showName = meta ? meta.name : 'TV Series';
  const year = meta?.year || 'Unknown';
  const cleanTitle = showName.replace(/[^a-zA-Z0-9_\- ]/g, '').trim();

  // 2. Fetch streams & season packs
  const streamData = await fetchStreams('series', id, sNum, 1);
  const seasonPacks = streamData.seasonPacks || [];
  const topPack = seasonPacks[0] || streamData.streams[0];
  const topMagnet = topPack ? topPack.magnet : '';

  // 3. Get episodes list for this season
  const seasonsMap = meta?.seasonsData || {};
  const episodes = seasonsMap[sNum] || [];

  const zip = new JSZip();

  // Root file 1: README Instructions
  const readmeContent = `========================================================================
XENMOVIES — SEASON ${sNum} COMPLETE BATCH PACK (.ZIP)
Show: ${showName} (${year})
Season: ${sNum}
Total Episodes: ${episodes.length || 'Full Season'}
Generated by: XENMOVIES Local Cinema Hub
========================================================================

HOW TO DOWNLOAD YOUR SEASON:
------------------------------------------------------------------------
Method 1 [RECOMMENDED - 1-Click All Episodes]:
  Double-click "Download_All_Season_${sNum}_Episodes.bat".
  This automatically sends the complete season batch pack to your
  Windows torrent client (qBittorrent / Free Download Manager / uTorrent),
  which will download every episode directly into one organized folder!

Method 2 [Direct Shortcut]:
  Double-click "Season_${sNum}_Complete_Batch_Pack.url" to launch the
  complete multi-file season batch immediately.

Method 3 [Manual Links]:
  Open "Episodes_Magnets_List.txt" to copy-paste exact magnet links into
  Internet Download Manager (IDM), JDownloader, or any torrent manager.

Method 4 [Portable Web Portal]:
  Open "Watch_or_Stream_Season_${sNum}.html" in any browser to stream
  episodes or trigger individual episode downloads.
========================================================================
`;
  zip.file('README_INSTRUCTIONS.txt', readmeContent);

  // Root file 2: Windows 1-Click Batch Script (.bat)
  const batScript = `@echo off
title XENMOVIES - Downloading ${cleanTitle} Season ${sNum} Batch Pack
color 0b
echo =======================================================================
echo    Starting Season Batch Download: ${cleanTitle} Season ${sNum}
echo =======================================================================
echo.
echo Launching Complete Season Batch Pack into your default Torrent Client...
echo (All episodes will be downloaded into one folder)
echo.
if "${topMagnet}"=="" (
    echo [!] No active batch magnet link found. Please check Episodes_Magnets_List.txt
) else (
    start "" "${topMagnet}"
    echo [OK] Season Batch launched successfully!
)
echo.
pause
`;
  zip.file(`Download_All_Season_${sNum}_Episodes.bat`, batScript);

  // Root file 3: Internet Shortcut to Complete Season Pack
  if (topMagnet) {
    const shortcutContent = `[InternetShortcut]\nURL=${topMagnet}\n`;
    zip.file(`Season_${sNum}_Complete_Batch_Pack.url`, shortcutContent);
  }

  // Root file 4: Full Episodes Magnets Text List
  let magnetsList = `========================================================================\n`;
  magnetsList += `${showName} - Season ${sNum} Episodes & Download Links\n`;
  magnetsList += `========================================================================\n\n`;

  if (topPack) {
    magnetsList += `--- COMPLETE SEASON BATCH PACK ---\n`;
    magnetsList += `Quality: ${topPack.quality} | Size: ${topPack.size} | Seeds: ${topPack.seeders}\n`;
    magnetsList += `Release: ${topPack.releaseTitle}\n`;
    magnetsList += `Magnet: ${topPack.magnet}\n\n`;
    magnetsList += `------------------------------------------------------------------------\n\n`;
  }

  magnetsList += `--- EPISODES GUIDE ---\n`;
  episodes.forEach(ep => {
    magnetsList += `Episode ${ep.episode}: ${ep.name || 'Episode ' + ep.episode}\n`;
    if (ep.overview) magnetsList += `Overview: ${ep.overview.slice(0, 150)}...\n`;
    magnetsList += `\n`;
  });

  zip.file(`Episodes_Magnets_List.txt`, magnetsList);

  // Root file 5: Portable Offline HTML Portal
  const htmlPortal = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <title>${showName} - Season ${sNum} Batch Hub</title>
  <style>
    body { background: #07080d; color: #e2e8f0; font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; padding: 30px; margin: 0; }
    .container { max-width: 900px; margin: auto; }
    h1 { color: #fff; margin-bottom: 5px; }
    .badge { display: inline-block; padding: 4px 10px; border-radius: 6px; font-size: 12px; font-weight: bold; background: #8b5cf6; color: white; margin-bottom: 20px; }
    .batch-card { background: #111422; border: 1px solid #06b6d4; border-radius: 16px; padding: 20px; margin-bottom: 30px; }
    .btn { display: inline-block; padding: 10px 18px; border-radius: 10px; font-size: 13px; font-weight: bold; text-decoration: none; margin-right: 10px; cursor: pointer; }
    .btn-primary { background: linear-gradient(135deg, #06b6d4, #3b82f6); color: white; }
    .btn-secondary { background: #1e2238; color: #a5b4fc; border: 1px solid #4338ca; }
    .ep-item { background: #0d101d; border: 1px solid #1e293b; padding: 14px; border-radius: 12px; margin-bottom: 10px; display: flex; align-items: center; justify-content: space-between; }
  </style>
</head>
<body>
  <div class="container">
    <h1>${showName} — Season ${sNum} Complete Hub</h1>
    <span class="badge">XENMOVIES Batch Pack</span>

    <div class="batch-card">
      <h3 style="margin-top:0; color:#38bdf8;">📦 Complete Season Batch Download</h3>
      <p style="color:#94a3b8; font-size:14px;">Release: ${topPack?.releaseTitle || 'Complete Season Pack'}</p>
      <p style="color:#cbd5e1; font-size:13px;">Quality: <strong>${topPack?.quality || 'HD'}</strong> | Size: <strong>${topPack?.size || 'Unknown'}</strong> | Seeds: <strong>${topPack?.seeders || 0}</strong></p>
      ${topMagnet ? `<a href="${topMagnet}" class="btn btn-primary">🧲 Download Season in Torrent Client</a>` : ''}
    </div>

    <h3>Episodes List (${episodes.length} Episodes)</h3>
    ${episodes.map(ep => `
      <div class="ep-item">
        <div>
          <strong style="color:#fff;">E${ep.episode}: ${ep.name || 'Episode ' + ep.episode}</strong>
          <div style="color:#64748b; font-size:12px; margin-top:4px;">${ep.overview ? ep.overview.slice(0, 100) + '...' : ''}</div>
        </div>
        <div>
          <a href="https://vidlink.pro/tv/${id}/${sNum}/${ep.episode}" target="_blank" class="btn btn-secondary">▶ Stream Online</a>
        </div>
      </div>
    `).join('')}
  </div>
</body>
</html>`;
  zip.file(`Watch_or_Stream_Season_${sNum}.html`, htmlPortal);

  // Subfolder: Individual Episodes (.url shortcuts)
  const epFolder = zip.folder(`Individual_Episodes`);
  episodes.forEach(ep => {
    const epNumStr = String(ep.episode).padStart(2, '0');
    const epShortcut = `[InternetShortcut]\nURL=https://vidlink.pro/tv/${id}/${sNum}/${ep.episode}\n`;
    const epTitleClean = (ep.name || `Episode_${epNumStr}`).replace(/[^a-zA-Z0-9_\-]/g, '_');
    epFolder.file(`Episode_${epNumStr}_${epTitleClean}.url`, epShortcut);
  });

  const buffer = await zip.generateAsync({
    type: 'nodebuffer',
    compression: 'DEFLATE',
    compressionOptions: { level: 6 }
  });

  return {
    buffer,
    filename: `${cleanTitle}_Season_${sNum}_Complete_Batch_Pack.zip`
  };
}

